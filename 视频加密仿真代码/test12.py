def rol32(x, n): return ((x << n) | (x >> (32 - n))) & 0xFFFFFFFF
def add31(a, b):
    x = a + b
    x = x + (x >> 31)
    return x & P31

def mul31(a, n): return ((a << n) | (a >> (31 - n))) & P31

def L1(x): return x ^ rol32(x,2) ^ rol32(x,10) ^ rol32(x,18) ^ rol32(x,24)
def L2(x): return x ^ rol32(x,8) ^ rol32(x,14) ^ rol32(x,22) ^ rol32(x,30)

def S(x):
    return (
        s1[x & 0xFF] |
        (s0[(x >> 8) & 0xFF] << 8) |
        (s1[(x >> 16) & 0xFF] << 16) |
        (s0[(x >> 24) & 0xFF] << 24)
    )

class ZUC256:
    def __init__(self, key, iv):
        self.s = [0]*16
        self.R1 = 0
        self.R2 = 0
        self._init(key, iv)

    def _load(self, a,b,c,d):
        return ((a<<23)|((b&0x7F)<<16)|(c<<8)|d)&P31

    def _init(self, k, iv):
        for i in range(16):
            self.s[i] = self._load(k[i], d2[i], k[i+16], iv[i%len(iv)])
        for _ in range(32):
            self._round(True)
        self._round(False)

    def _round(self, init):
        x0 = ((self.s[15]<<1)&0xFFFF0000)|(self.s[14]&0xFFFF)
        x1 = ((self.s[11]<<16)&0xFFFF0000)|((self.s[9]>>15)&0xFFFF)
        x2 = ((self.s[7]<<16)&0xFFFF0000)|((self.s[5]>>15)&0xFFFF)
        x3 = ((self.s[2]<<16)&0xFFFF0000)|((self.s[0]>>15)&0xFFFF)

        w  = (x0 ^ self.R1) + self.R2
        w1 = self.R1 + x1
        w2 = self.R2 ^ x2

        self.R1 = S(L1((w1<<16)|(w2>>16)))
        self.R2 = S(L2((w2<<16)|(w1>>16)))

        s16 = add31(self.s[0], mul31(self.s[0],8))
        s16 = add31(s16, mul31(self.s[4],20))
        s16 = add31(s16, mul31(self.s[10],21))
        s16 = add31(s16, mul31(self.s[13],17))
        s16 = add31(s16, mul31(self.s[15],15))
        if init: s16 = add31(s16, (w>>1)&P31)

        self.s = self.s[1:] + [s16]
        return w ^ x3

    def keystream(self, n):
        out = b""
        while len(out) < n:
            z = self._round(False)
            out += z.to_bytes(4, "big")
        return out[:n]

# ======================= HEVC =============================

START = b"\x00\x00\x01"
START4 = b"\x00\x00\x00\x01"

KEEP = {32,33,34,35,39,40}
I_ONLY = {19,20,21}

def nal_type(nalu): return (nalu[0] >> 1) & 0x3F

def split_annexb(data):
    pos = []
    i = 0
    while i < len(data)-3:
        if data[i:i+4] == START4:
            pos.append((i,4)); i+=4
        elif data[i:i+3] == START:
            pos.append((i,3)); i+=3
        else: i+=1
    out=[]
    for i,(p,l) in enumerate(pos):
        e = pos[i+1][0] if i+1<len(pos) else len(data)
        out.append((data[p:p+l], data[p+l:e]))
    return out

def kdf(master, feat, idx):
    k = hashlib.sha256(master+feat+struct.pack(">I",idx)).digest()
    iv = hashlib.sha256(feat+struct.pack(">I",idx)+master).digest()[:16]
    return k,iv

def hevc_i_encrypt(inp, outp, master):
    msh("HEVC", f"open {inp}")
    data = open(inp,"rb").read()
    nalus = split_annexb(data)
    msh("HEVC", f"nal count={len(nalus)}")

    out=[]
    enc_cnt=0
    idx=0

    for i,(sc,nalu) in enumerate(nalus):
        t = nal_type(nalu)
        if t in KEEP:
            msh("NAL", f"idx={i} type={t} keep")
            out.append((sc,nalu)); continue
        if t not in I_ONLY:
            msh("NAL", f"idx={i} type={t} skip")
            out.append((sc,nalu)); continue

        payload = nalu[2:]
        if len(payload)<=SKIP_PREFIX:
            msh("ENC", f"idx={i} type={t} too small")
            out.append((sc,nalu)); continue

        feat = payload[:32].ljust(32,b"\0")
        key,iv = kdf(master,feat,idx); idx+=1
        zuc = ZUC256(key,iv)
        body = payload[SKIP_PREFIX:]
        enc = zuc.keystream(len(body))
        out.append((sc,nalu[:2]+payload[:SKIP_PREFIX]+bytes(a^b for a,b in zip(body,enc))))
        enc_cnt+=1

        msh("ENC", f"idx={i} type={t} encrypt=YES len={len(body)}")

    msh("STAT", f"I-frame encrypted={enc_cnt}")
    open(outp,"wb").write(b"".join(sc+n for sc,n in out))

